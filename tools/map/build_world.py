"""Joins the built geometry with the authored tables into the game's world.

    uv run --project tools/map python tools/map/build_world.py

Reads `build/geometry.json` (from `build_map.py`), `region_attributes.csv`,
`extra_links.csv` and the population column of Natural Earth, and writes

    data/world/regions.json
    data/world/links.json

in the format of `data/SCHEMA.md` §2 and §3. Nothing here decides anything: the
regions come from `region_attributes.csv` in its row order, which *is* the index,
and the links are the geometry's land borders followed by the authored ones.

`tests/unit/test_world_content.gd` checks the result against `world.md` §7.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

import build_map as build

DATA = build.PROJECT / "data" / "world"

# The eight authored tiers, in the order SCHEMA §2 lists them.
ATTRIBUTES = [
    "compute",
    "connectivity",
    "wealth",
    "regulation",
    "research",
    "manufacturing",
    "industry",
    "isolation",
]


def populations() -> dict[str, int]:
    """Population per region: the sum of `POP_EST` over its rows in
    `region_groups.csv`.

    Deliberately *not* moved by the part overrides — a region keeps the people of
    the countries assigned to it, even where a far-flung part is drawn elsewhere.
    The error that leaves is below 0.5 % everywhere.
    """
    groups = build.read_groups()
    features = build.gpd.read_file(f"zip://{build.INPUT.as_posix()}")
    frame = features[[build.KEY, "POP_EST"]].copy()
    frame["region"] = frame[build.KEY].map(dict(zip(groups["adm0_a3"], groups["region"],
        strict=True)))
    frame = frame[frame["region"] != build.NO_REGION]
    totals = frame.groupby("region")["POP_EST"].sum()
    return {str(region): int(round(value)) for region, value in totals.items()}


def build_regions(geometry: dict, attributes: pd.DataFrame) -> list[dict]:
    anchors = {r["id"]: r["anchor"] for r in geometry["regions"]}
    people = populations()
    regions: list[dict] = []
    for row in attributes.itertuples():
        region = str(row.region)
        if region not in anchors:
            raise SystemExit(f"{region} has no geometry — run build_map.py first")
        regions.append(
            {
                "index": int(row.index),
                "id": region,
                "continent": str(row.continent),
                "population": people[region],
                "air_gapped": str(row.air_gapped).strip().lower() == "true",
                "anchor": anchors[region],
                "attributes": {name: int(getattr(row, name)) for name in ATTRIBUTES},
            }
        )
    return regions


def build_links(geometry: dict, known: set[str]) -> list[dict]:
    """Land links first, sorted, then the authored ones in CSV order.

    The file order is the simulation's iteration order and therefore part of the
    determinism contract (world.md §5.3).
    """
    links: list[dict] = []
    seen: set[tuple[str, str, str]] = set()

    for a, b in sorted(tuple(sorted(pair)) for pair in geometry["land_links"]):
        links.append({"a": a, "b": b, "kind": build.LAND_KIND})
        seen.add((a, b, build.LAND_KIND))

    extra = pd.read_csv(build.ROOT / "extra_links.csv")
    for row in extra.itertuples():
        a, b = sorted((str(row.a), str(row.b)))
        kind = str(row.kind)
        for endpoint in (a, b):
            if endpoint not in known:
                raise SystemExit(f"extra_links.csv names an unknown region: {endpoint}")
        if (a, b, kind) in seen:
            raise SystemExit(f"extra_links.csv doubles an existing link: {a}|{b}|{kind}")
        seen.add((a, b, kind))
        links.append({"a": a, "b": b, "kind": kind})
    return links


def write(path: Path, payload: dict) -> None:
    path.write_text(json.dumps(payload, indent="\t") + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    geometry_path = build.BUILD / "geometry.json"
    if not geometry_path.exists():
        print("no build/geometry.json — run build_map.py first")
        return 1
    geometry = json.loads(geometry_path.read_text(encoding="utf-8"))
    attributes = build.read_attributes()

    regions = build_regions(geometry, attributes)
    links = build_links(geometry, {r["id"] for r in regions})

    DATA.mkdir(parents=True, exist_ok=True)
    write(
        DATA / "regions.json",
        {
            "_comment": "Generated by tools/map/build_world.py — do not edit. "
            "The authored sources are tools/map/region_attributes.csv and Natural Earth.",
            "regions": regions,
        },
    )
    write(
        DATA / "links.json",
        {
            "_comment": "Generated by tools/map/build_world.py — do not edit. "
            "Land links come from the geometry, the rest from tools/map/extra_links.csv. "
            "The file order is the simulation's iteration order.",
            "links": links,
        },
    )

    kinds = pd.Series([link["kind"] for link in links]).value_counts().to_dict()
    total = sum(r["population"] for r in regions)
    print(f"regions: {len(regions)}, population {total:,}")
    print(f"links: {len(links)} ({', '.join(f'{k} {v}' for k, v in sorted(kinds.items()))})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
